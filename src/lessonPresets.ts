import { emptyPlan } from './db'
import type { LessonTemplate } from './types'

// Готовые заготовки уроков: по одной на каждый навык R&W и три служебных урока.
// Они лежат в коде (общие для всех, не правятся); «Сделать свою» копирует заготовку в свои.
//
// Структура заготовки — обратный дизайн урока: сначала цель и «хороший результат» (по чему видно,
// что получилось), потом теория, потом практика от совместной к самостоятельной, в конце — ДЗ.

interface PresetInput {
  id: string
  title: string
  skills: string[]
  durationMin?: number
  goals: string[]
  success: string[]
  theory: string[]
  practice: string[]
  homework: string
}

const lines = (items: string[]) => items.join('\n')

const preset = (p: PresetInput): LessonTemplate => ({
  id: `preset:${p.id}`,
  skills: p.skills,
  durationMin: p.durationMin ?? 60,
  homework: p.homework,
  createdAt: '',
  plan: {
    ...emptyPlan(),
    title: p.title,
    goals: lines(p.goals),
    success: lines(p.success),
    theory: lines(p.theory),
    practice: lines(p.practice),
    templateId: `preset:${p.id}`,
  },
})

export const isPreset = (id: string) => id.startsWith('preset:')

